/*
 * Build helper of the Android port: writes the app's launcher icon from the
 * original's own application icon, FUNICON, as an Android adaptive icon with
 * a vector drawable of one square per pixel, so the pixel art stays crisp at
 * any size.
 *
 * Android launchers only show icons built into the app, so this runs on the
 * build machine. The icon goes into the build directory, never into the
 * repository, which holds nothing of the original. Without the original,
 * the port's own icon is used instead.
 *
 * Usage: original_icon <folder of JWLTHIEF.EXE> <res output folder>
 */

#include "assets.h"
#include "fs.h"
#include "icon.h"

#include <errno.h>
#include <stdio.h>
#include <string.h>
#include <sys/stat.h>

#define ICON_NAME "FUNICON"
#define ADAPTIVE_NAME "ic_launcher_app"
#define DRAWABLE_NAME "ic_launcher_original"
#define PORT_DRAWABLE_NAME "ic_launcher_foreground"

/*
 * An adaptive icon is a 108-unit square of which launchers show about the
 * middle 66 units: a 32-pixel icon at 2 units per pixel takes the middle 64.
 */
#define CANVAS_UNITS 108
#define PIXEL_UNITS 2

/* Windows 3.x icons are at most 64 x 64. */
#define MAX_COLORS (64 * 64)

static bool make_dir(const char *path)
{
    return mkdir(path, 0755) == 0 || errno == EEXIST;
}

static FILE *open_output(const char *res_dir, const char *subdir, const char *name)
{
    char dir[FS_MAX_PATH];
    char file[FS_MAX_PATH];
    char file_name[64];

    snprintf(file_name, sizeof(file_name), "%s.xml", name);
    if (!fs_join_path(dir, sizeof(dir), res_dir, subdir) || !make_dir(dir)
        || !fs_join_path(file, sizeof(file), dir, file_name)) {
        return NULL;
    }
    return fopen(file, "w");
}

static bool write_adaptive_icon(const char *res_dir, const char *foreground)
{
    FILE *out = open_output(res_dir, "mipmap-anydpi-v26", ADAPTIVE_NAME);

    if (out == NULL) {
        return false;
    }
    fprintf(out,
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
            "<!-- Generated by original_icon at build time; never commit it. -->\n"
            "<adaptive-icon xmlns:android=\"http://schemas.android.com/apk/res/android\">\n"
            "    <background android:drawable=\"@color/ic_launcher_background\" />\n"
            "    <foreground android:drawable=\"@drawable/%s\" />\n"
            "    <monochrome android:drawable=\"@drawable/%s\" />\n"
            "</adaptive-icon>\n",
            foreground, foreground);
    return fclose(out) == 0;
}

static uint32_t pixel_color(const IconImage *image, int x, int y)
{
    const uint8_t *p = image->rgba + ((size_t)y * (size_t)image->width + (size_t)x) * 4;

    return ((uint32_t)p[3] << 24) | ((uint32_t)p[0] << 16) | ((uint32_t)p[1] << 8) | p[2];
}

/* The distinct opaque colors of the icon, in order of first appearance. */
static size_t list_colors(const IconImage *image, uint32_t *colors)
{
    size_t count = 0;
    int x, y;

    for (y = 0; y < image->height; y++) {
        for (x = 0; x < image->width; x++) {
            uint32_t color = pixel_color(image, x, y);
            size_t i = 0;

            while (i < count && colors[i] != color) {
                i++;
            }
            if (color >> 24 != 0 && i == count && count < MAX_COLORS) {
                colors[count++] = color;
            }
        }
    }
    return count;
}

/* One path per color, each pixel a square; transparent pixels are left out. */
static bool write_drawable(const char *res_dir, const IconImage *image)
{
    static uint32_t colors[MAX_COLORS];
    FILE *out = open_output(res_dir, "drawable", DRAWABLE_NAME);
    int left = (CANVAS_UNITS - image->width * PIXEL_UNITS) / 2;
    int top = (CANVAS_UNITS - image->height * PIXEL_UNITS) / 2;
    size_t color_count = list_colors(image, colors);
    size_t i;
    int x, y;

    if (out == NULL) {
        return false;
    }
    fprintf(out,
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
            "<!-- Generated by original_icon from the original's " ICON_NAME
            " at build time; never commit it. -->\n"
            "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n"
            "    android:width=\"%ddp\" android:height=\"%ddp\"\n"
            "    android:viewportWidth=\"%d\" android:viewportHeight=\"%d\">\n",
            CANVAS_UNITS, CANVAS_UNITS, CANVAS_UNITS, CANVAS_UNITS);
    for (i = 0; i < color_count; i++) {
        fprintf(out, "    <path android:fillColor=\"#%08X\" android:pathData=\"", colors[i]);
        for (y = 0; y < image->height; y++) {
            for (x = 0; x < image->width; x++) {
                if (pixel_color(image, x, y) == colors[i]) {
                    fprintf(out, "M%d,%dh%dv%dh-%dz", left + x * PIXEL_UNITS, top + y * PIXEL_UNITS,
                            PIXEL_UNITS, PIXEL_UNITS, PIXEL_UNITS);
                }
            }
        }
        fprintf(out, "\" />\n");
    }
    fprintf(out, "</vector>\n");
    return fclose(out) == 0;
}

int main(int argc, char **argv)
{
    Assets assets;
    IconImage image;
    NeBlob blob;
    bool written;

    if (argc != 3) {
        fprintf(stderr, "usage: original_icon <folder of JWLTHIEF.EXE> <res output folder>\n");
        return 2;
    }
    make_dir(argv[2]);
    if (assets_open(&assets, (const char *const *)&argv[1], 1) != ASSETS_OK) {
        printf("original_icon: no original Jewel Thief v1.4 in %s; using the port's own icon\n",
               argv[1]);
        return write_adaptive_icon(argv[2], PORT_DRAWABLE_NAME) ? 0 : 1;
    }
    if (!assets_icon(&assets, ICON_NAME, &blob) || !icon_decode(blob.data, blob.size, &image)) {
        assets_close(&assets);
        fprintf(stderr, "original_icon: " ICON_NAME " is missing or unreadable\n");
        return 1;
    }
    written = write_drawable(argv[2], &image) && write_adaptive_icon(argv[2], DRAWABLE_NAME);
    icon_free(&image);
    assets_close(&assets);
    if (written) {
        printf("original_icon: launcher icon made from the original's " ICON_NAME "\n");
    }
    return written ? 0 : 1;
}
